from extra import br, P

def TB(rows, head=None):
    """rows: [(th, td)]。td の中も「。」で改行する。head があると見出し行つき（トラブル表）。"""
    h, cls = '', ''
    if head:
        h = '<tr>' + ''.join(f'<th>{x}</th>' for x in head) + '</tr>'
        cls = ' class="tb-wrap"'
    body = ''.join(f'<tr><th>{th}</th><td>{br(td)}</td></tr>' for th, td in rows)
    return f'<div class="tbl"><table{cls}>{h}{body}</table></div>'

def LI(items, ordered=False):
    tag = 'ol class="art-ol"' if ordered else 'ul'
    end = 'ol' if ordered else 'ul'
    out = ''
    for it in items:
        if isinstance(it, tuple):
            out += f'<li><b>{it[0]}</b><br>{br(it[1])}</li>'
        else:
            out += f'<li>{br(it)}</li>'
    return f'<{tag}>{out}</{end}>'

def LINKS(links):
    return '<p>' + '<br>'.join(f'<a class="art-link" href="{h}">{t} →</a>' for h, t in links) + '</p>'

def SEC(en, jp, inner):
    return f'''  <section class="pg-sec w">
    <div class="pg-sec-hd"><h2>{en}</h2><p>{jp}</p></div>
    <div class="art">{inner}</div>
  </section>
'''

